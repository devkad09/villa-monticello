// Normalized suites ensure all required metadata (featuredImage, ctaLabel, bookingRef) is available
export const allSuitesNormalized: Suite[] = suites.map((s) => ({
  ...s,
  featuredImage: s.featuredImage || s.images[0],
  ctaLabel: s.ctaLabel || `Reserve ${s.name} Suite`,
  bookingRef: s.bookingRef || s.slug,
}));

export function getAllSuites(): Suite[] {
  return allSuitesNormalized;
}

export function getSuiteBySlug(slug: string): Suite | undefined {
  return allSuitesNormalized.find((s) => s.slug === slug);
}

export function getFeaturedSuite(): Suite {
  return allSuitesNormalized.find((s) => s.featured) || allSuitesNormalized[0];
}

export function getRelatedSuites(currentSlug: string, count: number = 3): Suite[] {
  return allSuitesNormalized.filter((s) => s.slug !== currentSlug).slice(0, count);
}
